import os
import json
import numpy as np
import onnxruntime as ort

def inspect_all():
    lines = []
    lines.append("# MODEL SPECIFICATION & INSPECTION (MODEL_SPEC.md)")
    lines.append("\n*Generated by scripts/inspect_models.py*\n")

    model_dir = "models"
    onnx_files = sorted([f for f in os.listdir(model_dir) if f.endswith(".onnx")])

    lines.append("## 1. ONNX Models Inspection\n")
    for onnx_file in onnx_files:
        path = os.path.join(model_dir, onnx_file)
        size_mb = os.path.getsize(path) / (1024 * 1024)
        lines.append(f"### Model: `{onnx_file}` ({size_mb:.2f} MB)")
        try:
            session = ort.InferenceSession(path, providers=["CPUExecutionProvider"])
            lines.append("**Inputs:**")
            for inp in session.get_inputs():
                lines.append(f"- `{inp.name}`: type={inp.type}, shape={inp.shape}")
            lines.append("\n**Outputs:**")
            for out in session.get_outputs():
                lines.append(f"- `{out.name}`: type={out.type}, shape={out.shape}")
            lines.append("")
        except Exception as e:
            lines.append(f"Error loading session: {e}\n")

    lines.append("## 2. NPZ File Inspection (`vieneu_v3_heads.npz`)\n")
    npz_path = os.path.join(model_dir, "vieneu_v3_heads.npz")
    if os.path.exists(npz_path):
        data = np.load(npz_path)
        lines.append(f"Entries count: {len(data.files)}\n")
        for k in sorted(data.files):
            arr = data[k]
            lines.append(f"- `{k}`: dtype={arr.dtype}, shape={arr.shape}, min={float(arr.min()):.4f}, max={float(arr.max()):.4f}")
        lines.append("")

    lines.append("## 3. Voices JSON Inspection (`voices_v3_turbo.json`)\n")
    voices_path = os.path.join(model_dir, "voices_v3_turbo.json")
    if os.path.exists(voices_path):
        with open(voices_path, "r", encoding="utf-8") as f:
            voices = json.load(f)
        lines.append(f"Total voices: {len(voices)}")
        lines.append(f"Voice names: {list(voices.keys())}\n")
        sample_voice = next(iter(voices.keys()))
        lines.append(f"Structure of sample voice `{sample_voice}`:")
        for k, v in voices[sample_voice].items():
            if isinstance(v, list):
                if len(v) > 0 and isinstance(v[0], list):
                    lines.append(f"- `{k}`: 2D list of shape [{len(v)}, {len(v[0])}] (element sample: {v[0][:5]})")
                else:
                    lines.append(f"- `{k}`: list of length {len(v)} (sample: {v[:5]})")
            else:
                lines.append(f"- `{k}`: {v}")
        lines.append("")

    lines.append("## 4. Config JSON Inspection (`config.json`)\n")
    cfg_path = os.path.join(model_dir, "config.json")
    if os.path.exists(cfg_path):
        with open(cfg_path, "r", encoding="utf-8") as f:
            cfg = json.load(f)
        lines.append("```json")
        lines.append(json.dumps(cfg, indent=2))
        lines.append("```\n")

    lines.append("## 5. Tokenizer & Dictionaries\n")
    tok_path = os.path.join(model_dir, "tokenizer.json")
    if os.path.exists(tok_path):
        with open(tok_path, "r", encoding="utf-8") as f:
            tok = json.load(f)
        vocab = tok.get("model", {}).get("vocab", {})
        lines.append(f"- `tokenizer.json`: vocab_size={len(vocab)}")
        special_tokens = [k for k in vocab.keys() if k.startswith("<|") or k.startswith("__")]
        lines.append(f"- Special tokens count: {len(special_tokens)}")
        lines.append(f"- Special tokens: {special_tokens}")

    g2p_path = os.path.join(model_dir, "vieneu_vi_g2p.json")
    if os.path.exists(g2p_path):
        with open(g2p_path, "r", encoding="utf-8") as f:
            g2p = json.load(f)
        lines.append(f"- `vieneu_vi_g2p.json`: {len(g2p)} word entries (sample: 'việt': '{g2p.get('việt', '')}')")

    with open("MODEL_SPEC.md", "w", encoding="utf-8") as f:
        f.write("\n".join(lines))

    print("SUCCESS: MODEL_SPEC.md written successfully.")

if __name__ == "__main__":
    inspect_all()
